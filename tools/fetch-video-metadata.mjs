// Fetch REAL metadata for every lecture mapped in lib/chapter-videos.ts and
// write it to lib/generated/video-metadata.ts, which the /video route uses to
// emit VideoObject structured data.
//
// WHY IT IS FETCHED RATHER THAN HAND-WRITTEN
// ------------------------------------------
// VideoObject requires `name`, `description`, `thumbnailUrl` and `uploadDate`.
// Search Console (2026-08-08) reports the site's one detected video as "Video
// isn't on a watch page", i.e. no video on this site is eligible for video
// results at all.
//
// `uploadDate` is the trap. It is a factual claim about when the Captain
// published a lecture, and this codebase has already shipped fabricated dates
// once — six guide dates were invented, two of them announcing May 2024 for
// files created in July 2026 (see CLAUDE.md, "Dates are claims"). So no date
// here is guessed, derived from a filename, or taken from a file mtime: every
// value is read from YouTube's own watch page for that video ID. If a fetch
// fails, that video is written with `null` metadata and simply gets no
// VideoObject — an absent claim beats an invented one.
//
// Re-run after adding lectures to lib/chapter-videos.ts:
//   node tools/fetch-video-metadata.mjs

import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";

const src = readFileSync(join(ROOT, "lib", "chapter-videos.ts"), "utf8");
const ids = [...new Set([...src.matchAll(/id:\s*"([A-Za-z0-9_-]{11})"/g)].map(m => m[1]))];
console.log(`fetching metadata for ${ids.length} lectures...`);

const dec = s => s
  .replace(/\\u0026/g, "&").replace(/\\"/g, '"').replace(/\\\\/g, "\\")
  .replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&#39;/g, "'")
  .replace(/&lt;/g, "<").replace(/&gt;/g, ">");

// ISO-8601 duration, which is what VideoObject.duration expects.
const iso = secs => {
  const s = Number(secs) || 0;
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), r = s % 60;
  return `PT${h ? h + "H" : ""}${m ? m + "M" : ""}${r || (!h && !m) ? r + "S" : ""}`;
};

const out = {};
let ok = 0, failed = 0;

for (const id of ids) {
  try {
    const r = await fetch(`https://www.youtube.com/watch?v=${id}`, { headers: { "User-Agent": UA } });
    const h = await r.text();
    const name = (h.match(/<meta name="title" content="([^"]*)"/) || [])[1];
    const uploadDate = (h.match(/"uploadDate":"([^"]*)"/) || [])[1];
    const seconds = (h.match(/"lengthSeconds":"(\d+)"/) || [])[1];
    const description = (h.match(/<meta name="description" content="([^"]*)"/) || [])[1];

    // name + uploadDate are the two that cannot be substituted. Without either,
    // write null and let the page skip the markup rather than assert a guess.
    if (!name || !uploadDate) { out[id] = null; failed++; console.log(`  ${id}  INCOMPLETE — no VideoObject will be emitted`); continue; }

    out[id] = {
      name: dec(name),
      description: description ? dec(description).slice(0, 300) : "",
      uploadDate,
      duration: seconds ? iso(seconds) : "",
      thumbnailUrl: `https://i.ytimg.com/vi/${id}/hqdefault.jpg`,
    };
    ok++;
    console.log(`  ${id}  ${out[id].uploadDate.slice(0, 10)}  ${out[id].name.slice(0, 58)}`);
  } catch (e) {
    out[id] = null; failed++;
    console.log(`  ${id}  FETCH FAILED (${String(e).slice(0, 40)})`);
  }
}

const body = `// GENERATED by tools/fetch-video-metadata.mjs — do not edit by hand.
// Every value here was read from YouTube's own watch page for that video ID.
// Nothing is inferred: a lecture whose title or uploadDate could not be read is
// stored as null and gets no VideoObject, because an absent claim beats an
// invented one. Re-run the tool after adding lectures to lib/chapter-videos.ts.

export type VideoMeta = {
  name: string;
  description: string;
  uploadDate: string;
  duration: string;
  thumbnailUrl: string;
};

export const VIDEO_METADATA: Record<string, VideoMeta | null> = ${JSON.stringify(out, null, 2)};
`;

mkdirSync(join(ROOT, "lib", "generated"), { recursive: true });
writeFileSync(join(ROOT, "lib", "generated", "video-metadata.ts"), body, "utf8");
console.log(`\nwrote lib/generated/video-metadata.ts — ${ok} with full metadata, ${failed} skipped`);
