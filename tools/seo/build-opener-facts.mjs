#!/usr/bin/env node
/**
 * Build lib/generated/opener-key-facts.ts from TOPIC_OPENERS_FOR_REVIEW.tsv - the 745 sentences
 * Gini already quotes, each VERBATIM from one of the Captain's published chapters.
 *
 *   node tools/seo/build-opener-facts.mjs
 *
 * These become the "Key facts" revision box under a chapter's notes (HtmlNotesPage), but ONLY for
 * subjects listed in lib/opener-key-facts.ts APPROVED_OPENER_SUBJECTS, because CLAUDE.md records
 * the TSV as "OPEN AND HIS: ... wants his eye". Nothing is composed; filters only REMOVE rows:
 * too short or too long, a worked example lifted out of context, a forbidden source name, a
 * duplicate. At most five per chapter, in chapter order.
 *
 * The output is imported ONLY by server code (the notes route), never by lib/chapter-key-facts.ts,
 * which Gini pulls into the bundle on every page - adding 745 sentences there would put ~100 KB on
 * every route (the bundle defect CLAUDE.md warns about).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const rows = readFileSync(join(ROOT, "TOPIC_OPENERS_FOR_REVIEW.tsv"), "utf8").split(/\r?\n/).slice(1).filter(Boolean);
const names = JSON.parse(readFileSync(join(ROOT, "tools", "forbidden-source-names.json"), "utf8")).names;
const forbidden = new RegExp(names.map((n) => n.split(/\s+/).map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("[\\s.\\-]*")).join("|"), "i");

const out = {};
let kept = 0, dropped = 0;
for (const row of rows) {
  const [key, heading, sentenceRaw] = row.split("\t");
  const sentence = (sentenceRaw || "").replace(/\s+([.,;:!?)])/g, "$1").trim();   // closes stray spaces only
  const bad = !key || !heading || sentence.length < 40 || sentence.length > 300 ||
    /^(example|e\.g\.|note|for example)\b/i.test(sentence) || forbidden.test(sentence + " " + heading);
  const list = (out[key] ||= []);
  if (bad || list.length >= 5 || list.some((f) => f.fact === sentence)) { dropped++; continue; }
  list.push({ term: heading.trim(), fact: sentence });
  kept++;
}
const body = JSON.stringify(out);
writeFileSync(join(ROOT, "lib", "generated", "opener-key-facts.ts"),
  `// GENERATED by tools/seo/build-opener-facts.mjs from TOPIC_OPENERS_FOR_REVIEW.tsv - do not edit.\n` +
  `// Verbatim sentences from the Captain's published chapters. SERVER-ONLY: never import from client code.\n` +
  `import type { KeyFact } from "../chapter-key-facts";\n\n` +
  `export const OPENER_FACTS: Record<string, KeyFact[]> = JSON.parse(${JSON.stringify(body)});\n`);
console.log(`kept ${kept} sentences across ${Object.keys(out).filter((k) => out[k].length).length} chapters; dropped ${dropped}`);
