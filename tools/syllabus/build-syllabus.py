"""Write lib/generated/dgca-syllabus.ts from the parsed CAR and the chapter map.

  python tools/syllabus/parse-car-7b4.py <CAR pdf>   # -> car-7b4.json (the CAR's text)
  python tools/syllabus/check-map.py                  # map vs chapter text (needs out/_gini)
  python tools/syllabus/build-syllabus.py             # -> lib/generated/dgca-syllabus.ts

The pages decide at build time which mapped chapters actually serve notes, so a
chapter written later starts appearing without touching this file.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
car = json.loads((ROOT / "tools/syllabus/car-7b4.json").read_text(encoding="utf-8"))
cmap = {k: v for k, v in json.loads((ROOT / "tools/syllabus/chapter-map.json").read_text(encoding="utf-8")).items()
        if not k.startswith("_")}

PAPERS = [
    ("air-navigation", "A"),
    ("meteorology", "B"),
    ("air-regulations", "C"),
    ("technical-general", "D"),
]

papers = []
for slug, app in PAPERS:
    a = car[app]
    sections = []
    for s in a["sections"]:
        sec = {
            "key": s["key"],
            "num": s["num"],
            "title": s["title"],
            "items": s["items"],
            "chapters": cmap.get(f'{app}:{s["key"]}', []),
            "topics": [
                {
                    "letter": b["letter"],
                    "title": b["title"],
                    "items": b["items"],
                    "chapters": cmap.get(f'{app}:{s["key"]}.{b["letter"]}', []),
                }
                for b in s["subs"]
            ],
        }
        sections.append(sec)
    papers.append({"slug": slug, "appendix": app, "appendixTitle": a["title"], "sections": sections})

payload = json.dumps(papers, ensure_ascii=False, separators=(",", ":"))
out = ROOT / "lib/generated/dgca-syllabus.ts"
out.write_text(
    "// GENERATED by tools/syllabus/build-syllabus.py — do not edit by hand.\n"
    "// Text: DGCA CAR Section 7 Series B Part IV, Issue III (16 June 2011), Appendices A-D,\n"
    "// as published. Chapter links: tools/syllabus/chapter-map.json, checked by check-map.py.\n\n"
    "export type SyllabusItem = { text: string; children: string[] };\n"
    "export type SyllabusTopic = { letter: string; title: string; items: SyllabusItem[]; chapters: string[] };\n"
    "export type SyllabusSection = { key: string; num: string; title: string; items: SyllabusItem[]; chapters: string[]; topics: SyllabusTopic[] };\n"
    "export type SyllabusPaper = { slug: string; appendix: string; appendixTitle: string; sections: SyllabusSection[] };\n\n"
    f"export const SYLLABUS_PAPERS: SyllabusPaper[] = JSON.parse({json.dumps(payload, ensure_ascii=False)});\n",
    encoding="utf-8",
)
print("wrote", out.relative_to(ROOT), len(payload), "chars,", len(papers), "papers")
