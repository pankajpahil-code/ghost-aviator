// Builds lib/generated/met-verified.ts from the per-chapter verified modules.
// - user-facing `exp` is sanitised of all source/author names (branding rule)
// - hard-fails if any banned name would reach a student-visible field
// Re-run after editing any chapter module:  node tools/met-verify/build-met-verified.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));

// Registry — extend as each chapter is verified.
const CHAPTERS = [
  { mod: "./ch1-atmosphere.mjs", exp: "CH1", id: "met-1", topic: "The Atmosphere" },
  { mod: "./ch2-pressure.mjs",   exp: "CH2", id: "met-2", topic: "Atmospheric Pressure" },
  { mod: "./ch3-temperature.mjs", exp: "CH3", id: "met-3", topic: "Temperature" },
  { mod: "./ch4-density.mjs",    exp: "CH4", id: "met-4", topic: "Air Density" },
  { mod: "./ch5-humidity.mjs",   exp: "CH5", id: "met-5", topic: "Humidity" },
  { mod: "./ch6-wind.mjs",       exp: "CH6", id: "met-6", topic: "Wind" },
  { mod: "./ch7-visibility.mjs", exp: "CH7", id: "met-7", topic: "Visibility & Fog" },
  { mod: "./ch8-clouds.mjs",     exp: "CH8", id: "met-8", topic: "Vertical Motion & Clouds" },
  { mod: "./ch10-optical.mjs",   exp: "CH10", id: "met-10", topic: "Optical Phenomena" },
];

const BANNED = /\b(IC ?Joshi|Joshi|CAE|Oxford|RK ?Bali|Surender|Sahil|Redbird|Keith Williams|ECQB)\b/i;

// Strip internal citations → clean student-facing explanation.
function toExp(cite) {
  let e = cite
    .replace(/\s*\[[^\]]*\]/g, "")                 // drop [2nd reviewer …] internal notes
    .replace(/\s*\([^)]*\)/g, "")                 // drop parentheticals (usually the source ref)
    .replace(/\.\s*(IC ?Joshi|CAE|Oxford)[^.]*\./gi, ".") // drop "… IC Joshi marked …" sentences
    .replace(/\s*—[^.]*$/g, "")                   // drop trailing "— WRONG …"
    .replace(/\s*(Live site|The live site|Live notes-bank)[^.]*\.?/gi, "")
    .replace(/\b(Applied|Logged for your override|Confirm[^.]*|please confirm[^.]*)\.?/gi, "")
    .replace(/\s{2,}/g, " ")
    .trim();
  if (!/[.!?]$/.test(e) && e) e += ".";
  return e;
}

const out = [];
const doneChapters = new Set();
for (const ch of CHAPTERS) {
  const m = await import(ch.mod);
  const arr = m[ch.exp];
  doneChapters.add(ch.id);
  for (const q of arr) {
    const exp = toExp(q.cite);
    const rec = {
      subjectIds: ["meteorology", "atpl-meteorology"],
      chapterId: ch.id,
      subtopic: ch.topic,
      source: "Ghost Aviator — verified",
      q: q.q,
      opts: q.opts,
      ans: q.ans,
      exp,
    };
    // branding guard: nothing student-visible may name a source/author
    for (const field of [rec.q, rec.exp, ...rec.opts]) {
      if (BANNED.test(field)) throw new Error(`BANNED source name in student-visible text: "${field}"`);
    }
    if (rec.ans < 0 || rec.ans >= rec.opts.length) throw new Error(`bad ans index in: ${rec.q}`);
    out.push(rec);
  }
}

// ── Workflow-verified chapters (met-9, met-11..met-29) ────────────────────
const wfPath = path.join(here, "wf-verified.json");
if (fs.existsSync(wfPath)) {
  const wf = JSON.parse(fs.readFileSync(wfPath, "utf8"));
  for (const ch of wf) {
    if (!ch.questions) continue;
    doneChapters.add(ch.cid);
    for (const q of ch.questions) {
      if (q.status === "DROP") continue;              // broken question, removed
      const exp = toExp(q.cite || "");
      const rec = {
        subjectIds: ["meteorology", "atpl-meteorology"],
        chapterId: ch.cid,
        subtopic: ch.topic,
        source: "Ghost Aviator — verified",
        q: q.q, opts: q.opts, ans: q.ans, exp,
      };
      for (const field of [rec.q, rec.exp, ...rec.opts]) {
        if (BANNED.test(field)) throw new Error(`BANNED source name (wf ${ch.cid}): "${field}"`);
      }
      if (rec.ans < 0 || rec.ans >= rec.opts.length) throw new Error(`bad ans (wf ${ch.cid}): ${rec.q}`);
      out.push(rec);
    }
  }
}

const ts = `import type { DemoQuestion } from "../demo-questions";

// AUTO-GENERATED by tools/met-verify/build-met-verified.mjs — do not edit by hand.
// Verified Meteorology question bank: every answer cross-checked against the
// Oxford/CAE ATPL Meteorology manual + standard aviation meteorology, book
// errors corrected, garbled text repaired, duplicates removed.
// Verified chapters: ${[...doneChapters].join(", ")}
export const VERIFIED_MET_CHAPTERS = new Set(${JSON.stringify([...doneChapters])});

export const MET_VERIFIED: DemoQuestion[] = ${JSON.stringify(out, null, 2)};
`;

const dest = path.join(here, "..", "..", "lib", "generated", "met-verified.ts");
fs.writeFileSync(dest, ts, "utf8");
console.log(`Wrote ${out.length} verified questions across ${doneChapters.size} chapter(s) → ${dest}`);
console.log(`Chapters done: ${[...doneChapters].join(", ")}`);
