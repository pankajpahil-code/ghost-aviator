import json, re, sys, os, collections
W, outts, outjson = sys.argv[1], sys.argv[2], sys.argv[3]
allr = json.load(open(os.path.join(W, 'final', 'all.json'), encoding='utf-8'))
SUBTOPIC = {
    'PSR & PET': 'Critical Point and Point of No Return', 'SCALE': 'Scale', 'DESCENTS': 'Climb, Descent and Glidepath',
    'CIRCLES': 'Great Circles, Rhumb Lines and Departure', 'CHART THEORY': 'Chart Properties',
    'MAGNETISM & COMPASSES': 'Magnetism and Compasses', 'INS IRS FMS EFIS': 'INS, IRS, FMS and EFIS',
    'SOLAR SYSTEM & TIME': 'Earth, Time and Sunrise', 'CRP5': 'Flight Computer (CX-3)',
}
DEG = re.compile(r'(?<=\d)\s?o(?=\s|[.,;:)/\\\-–NSEWTMRLC(]|$)')


TYPO = [('How for can', 'How far can'), ('ILF GPP angle', 'ILS GP angle'), ('Direct Meracator', 'Direct Mercator'), ('Direct Merecator', 'Direct Mercator'),
        ('Stereographical projection', 'Stereographic projection'), ('How does the FMS calculating groundspeed', 'How does the FMS calculate groundspeed'),
        ('form the ', 'from the '), ('steering form', 'steering from'), ('ration between', 'ratio between'), ('sis used', 'is used'),
        ('100 stature miles', '100 statute miles'), ('When suing a', 'When using a'), ('and returns in one hour', 'and return in one hour'),
        ('Input form DME', 'Input from DME'), ('detector unit form', 'detector unit from'), ('TASS from ADC', 'TAS from ADC')]


def clean(s):
    s = s.replace('\t', ' ')
    for a, b in TYPO:
        s = s.replace(a, b)
    s = DEG.sub('°', s)
    s = re.sub(r'\s+', ' ', s).strip()
    s = re.sub(r'\s+([.,?])', r'\1', s)
    return s


def opt(s):
    s = clean(s)
    s = re.sub(r'\.$', '', s)
    return s


def tl(s):
    return '`' + s.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${') + '`'


live = [r for r in allr if r['status'] in ('VERIFIED', 'CORRECTED')]
live.sort(key=lambda r: (r['ch'], r['sec'], r['n']))
rows = []
for r in live:
    subj = ['instrumentation'] if r['ch'].startswith('inst-') else ['air-navigation', 'atpl-navigation']
    q = clean(r['q'])
    opts = [opt(o) for o in r['opts']]
    assert len(set(o.lower() for o in opts)) == 4, (r['sec'], r['n'], opts)
    rows.append(dict(subjectIds=subj, chapterId=r['ch'], subtopic=SUBTOPIC[r['sec']], q=q, opts=opts, ans=r['ans'], exp=clean(r['exp']),
                     _sec=r['sec'], _n=r['n'], _status=r['status'], _notes=r.get('notes', [])))
by = collections.Counter(x['chapterId'] for x in rows)
lines = ['import type { DemoQuestion } from "../demo-questions";', '',
         '// AUTO-GENERATED by tools/audit/gen-nav-bank-2026-10-23/build.py from decisions.json - do not edit by hand.',
         '// General Navigation practice bank, checked 2026-10-23: every key re-worked from the question data',
         '// (numerical items) or reasoned against the source working (theory items); explanations written fresh.',
         f'// {len(rows)} questions . per chapter: {json.dumps(dict(sorted(by.items())))}',
         'export const GEN_NAV_PRACTICE: DemoQuestion[] = [']
for x in rows:
    lines += ['  {',
              f'    subjectIds: {json.dumps(x["subjectIds"])},',
              f'    chapterId: "{x["chapterId"]}",',
              f'    subtopic: {tl(x["subtopic"])},',
              f'    source: `General Navigation practice bank`,',
              f'    q: {tl(x["q"])},',
              f'    opts: [{", ".join(tl(o) for o in x["opts"])}],',
              f'    ans: {x["ans"]},',
              f'    exp: {tl(x["exp"])},',
              '  },']
lines += ['];', '']
open(outts, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
json.dump(rows, open(outjson, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(len(rows), dict(sorted(by.items())))
