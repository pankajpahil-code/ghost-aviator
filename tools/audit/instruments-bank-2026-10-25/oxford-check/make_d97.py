"""Build ins/dec/d97_oxford.py: questions held as 'two defensible answers' that the Oxford book settles
(Captain's ruling 2026-10-26). Keys and explanations come from oxford_0/1.json (quotes verified against the
Oxford text); repeats of live questions and items that would contradict a live question are left out."""
import json, os
D = os.path.dirname(os.path.abspath(__file__))
R = {r['id']: r for f in ('oxford_0.json', 'oxford_1.json') for r in json.load(open(os.path.join(D, f), encoding='utf-8'))}
KEEP = ['ALTEMETER|11', 'ALTEMETER|16', 'ASI|47', 'MACH|33', 'TURN/SLIP|26',
        'AUTOFLIGHT|79', 'AUTOFLIGHT|87', 'AUTOFLIGHT|96', 'AUTOFLIGHT|100', 'AUTOFLIGHT|108', 'AUTOFLIGHT|110',
        'AUTOFLIGHT|111', 'AUTOFLIGHT|120', 'EICAS/ECAM|3', 'EICAS/ECAM|19', 'ENGINE|11', 'ENGINE|19',
        'ENGINE|37', 'TEMP|6', 'FUEL|2', 'FUEL|4', 'FUEL|13', 'COMPASS|36', 'COMPASS|61', 'WARN/REC|8',
        'WARN/REC|11', 'TCAS|15']
FIX = {
 'ALTEMETER|11': dict(opt={'c': 'The actual pressure measured at mean sea level.'}),
 'ALTEMETER|16': dict(opt={'c': 'One will under read close to the ground.', 'd': 'The ADC will compensate automatically, so both will read correctly.'}),
 'ASI|47': dict(opt={'a': 'VNE.', 'b': 'VMO.', 'd': 'VNO.'}),
 'MACH|8': dict(opt={'b': 'Vary only with Mach number; they are independent of temperature.'}),
 'MACH|33': dict(q="If total air temperature increases by 5 degrees C during a constant Mach number descent, what will happen to CAS?",
                 exp="In a constant-Mach descent the air gets warmer and denser, so the CAS rises. As a rule of thumb, a 5 °C rise in total air temperature goes with about 10 kt more CAS."),
 'TURN/SLIP|26': dict(opt={'a': 'More right rudder.'},
                      exp="With the ball out to the right in a left turn the aircraft is skidding: there is not enough bank for the rate of turn. Increase the left bank."),
 'AUTOFLIGHT|87': dict(q="An autoland procedure is complete when?",
                       exp="The autoland procedure is complete at the start of the ground roll, once the aircraft has touched down."),
 'ENGINE|37': dict(opt={'a': 'Oil pressure at the fixed crown of an epicyclic reduction gear of the main engine gearbox.', 'd': 'Quantity of light passing through a rack-wheel attached to a transmission shaft.'}),
 'FUEL|4': dict(q="A capacitive fuel gauging system can calculate the mass of fuel by using the fact that?",
                opt={'a': 'Fuel dielectric constant is proportional to density and twice that of air.', 'b': 'Fuel dielectric constant is equal to 1/density and proportional to that of air.',
                     'c': 'Fuel dielectric constant is equal to density and proportional to that of air.', 'd': 'Fuel dielectric constant is proportional to 1/density and equal to that of air.'}),
}
out = ['# Generated by audit_ins/make_d97.py. Questions first held as "two defensible answers", settled from the',
       '# Oxford instrumentation book on the Captain\'s ruling of 2026-10-26 ("check oxford book source for answers").',
       'NOTE = "Settled from the Oxford instrumentation book on the Captain\'s ruling (2026-10-26)."',
       'PATCH = {']
for i in KEEP:
    r = R[i]
    assert r['verdict'] == 'SETTLED', i
    sec, n = i.split('|')
    e = dict(drop=None, ans=r['letter'].lower(), exp=r['explanation'], status='VERIFIED')
    e.update(FIX.get(i, {}))
    out.append(f" ({sec!r}, {int(n)}): dict(note=NOTE, **{e!r}),")
out.append('}')
open(os.path.join(D, '..', 'ins', 'dec', 'd97_oxford.py'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(KEEP))
