/**
 * GINI'S TRUTH LAYER — the router, and the light half of what he knows.
 *
 * ────────────────────────────────────────────────────────────────────────────
 * THE ONE RULE, AND IT IS STRUCTURAL, NOT ASPIRATIONAL:
 *
 *   Gini may only ever say sentences that are ALREADY WRITTEN AND STORED in
 *   this repository. He retrieves; he never composes. There is no model call
 *   in this file and there must never be one.
 *
 * Why it is built this way. Iron Rule 1 says never publish a guessed answer —
 * wrong answers harm student pilots. A language model asked to "explain this
 * question" will produce fluent, confident, occasionally wrong aviation
 * teaching, and it would be doing so in the mascot's voice, on the site that
 * publishes /how-answers-are-verified. The only defence that actually holds is
 * to make invention impossible rather than unlikely: every string Gini speaks
 * comes out of a data file a human wrote.
 *
 * When there is nothing verified to say, he says so. That refusal is a feature.
 * It is also honest in a way no competitor in this market is.
 * ────────────────────────────────────────────────────────────────────────────
 *
 * HOW HE IS PUT TOGETHER (2026-08-20 rebuild):
 *
 *   types.ts      the reply shape and the refusal sentences
 *   match.ts      how a typed sentence is matched to a stored one
 *   context.ts    which page the student is standing on
 *   persona.ts    greetings, small talk, study wisdom      (light)
 *   marketing.ts  what the Captain offers, and when to say so  (light)
 *   knowledge.ts  THIS FILE — FAQ, structure, and the router (light)
 *   deep.ts       the 4,400-question bank             (LAZY — see below)
 *
 * "Light" means it ships with the page. deep.ts does not: it is pulled in with
 * a dynamic import the first time a student asks something the light layer
 * cannot answer, because Gini renders on every route and the bank is megabytes.
 * Use ask() when you need a synchronous answer, askDeep() when you can await.
 *
 * Corpus figures come from lib/gini/generated/corpus-stats.ts, regenerated by
 * `npx tsx tools/gini/build-corpus-stats.mts` and drift-checked by
 * `npx tsx tools/audit/gini-selftest.mts`.
 */

